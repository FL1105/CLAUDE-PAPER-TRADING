"""API probe: hit every endpoint once, record what the REAL API returns.

Assumptions:
    * Nothing about the API is trusted until this has run. It records JSON key
      shapes, pagination limits (max ``limit``, ``offset`` behaviour), rate-limit
      headers and fee-related fields, saves raw responses to
      ``tests/fixtures/live/`` and checks each one against the adapter layer.

Failure modes guarded against:
    * Coding against fabricated schemas: drift between the live payload and
      ``data.schemas`` is reported per endpoint, loudly.
    * Pretending deep history exists: pagination is probed explicitly and the
      achievable window is written into docs/ASSUMPTIONS.md.
    * Silent probe failures: every step's error is recorded in the report rather
      than swallowed; the probe continues so one bad endpoint does not hide others.
"""

from __future__ import annotations

import json
import logging
import time
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from polybot.data import schemas
from polybot.data.client import ApiError, PolymarketClient

log = logging.getLogger("polybot.probe")

BEGIN = "<!-- PROBE:BEGIN (auto-generated by `polybot probe`; do not edit by hand) -->"
END = "<!-- PROBE:END -->"
HEADER_HINTS = ("ratelimit", "rate-limit", "retry-after", "x-ratelimit", "cf-cache", "age")


@dataclass
class StepResult:
    name: str
    ok: bool
    status: int | None = None
    shape: Any = None
    headers: dict[str, str] = field(default_factory=dict)
    note: str = ""
    count: int | None = None


@dataclass
class ProbeReport:
    started_ts: int
    steps: list[StepResult] = field(default_factory=list)
    pagination: dict[str, list[dict[str, Any]]] = field(default_factory=dict)
    drift: dict[str, str] = field(default_factory=dict)
    fee_fields: dict[str, Any] = field(default_factory=dict)
    samples: dict[str, str] = field(default_factory=dict)

    def to_json(self) -> dict[str, Any]:
        return {
            "started_ts": self.started_ts,
            "steps": [s.__dict__ for s in self.steps],
            "pagination": self.pagination,
            "drift": self.drift,
            "fee_fields": self.fee_fields,
            "samples": self.samples,
        }


def shape_of(obj: Any, depth: int = 0) -> Any:
    """Compact structural description: keys -> type names, lists -> [len, shape of first]."""
    if depth > 3:
        return type(obj).__name__
    if isinstance(obj, dict):
        return {k: shape_of(v, depth + 1) for k, v in sorted(obj.items())}
    if isinstance(obj, list):
        return {"__list_len__": len(obj), "__item__": shape_of(obj[0], depth + 1) if obj else None}
    return type(obj).__name__


def _items(payload: Any) -> list[Any]:
    if isinstance(payload, list):
        return payload
    if isinstance(payload, dict):
        for k in ("data", "history", "markets", "results"):
            if isinstance(payload.get(k), list):
                return list(payload[k])
    return []


class Prober:
    def __init__(self, client: PolymarketClient, fixtures_dir: Path) -> None:
        self.c = client
        self.fixtures_dir = fixtures_dir
        self.report = ProbeReport(started_ts=int(time.time()))

    def _headers(self) -> dict[str, str]:
        r = self.c.http.last_response
        if r is None:
            return {}
        return {k: v for k, v in r.headers.items() if any(h in k.lower() for h in HEADER_HINTS)}

    def step(self, name: str, fn: Callable[[], Any], save: bool = True) -> Any:
        try:
            payload = fn()
        except ApiError as exc:
            self.report.steps.append(StepResult(name, False, exc.status, note=str(exc)[:300]))
            log.warning("probe %s failed: %s", name, exc)
            return None
        resp = self.c.http.last_response
        res = StepResult(
            name,
            True,
            resp.status_code if resp is not None else None,
            shape=shape_of(payload),
            headers=self._headers(),
            count=len(payload) if isinstance(payload, list) else None,
        )
        self.report.steps.append(res)
        if save:
            self.fixtures_dir.mkdir(parents=True, exist_ok=True)
            with (self.fixtures_dir / f"{name}.json").open("w", encoding="utf-8") as fh:
                json.dump(payload, fh, indent=1, sort_keys=True)
        return payload

    def paginate(
        self, label: str, fn: Callable[..., Any], limits: list[int], offsets: list[int]
    ) -> None:
        rows: list[dict[str, Any]] = []
        for lim in limits:
            try:
                n = len(_items(fn(limit=lim)))
                rows.append({"limit": lim, "offset": 0, "returned": n})
            except ApiError as exc:
                rows.append({"limit": lim, "offset": 0, "error": exc.status, "msg": str(exc)[:160]})
        for off in offsets:
            try:
                n = len(_items(fn(limit=limits[0], offset=off)))
                rows.append({"limit": limits[0], "offset": off, "returned": n})
            except ApiError as exc:
                rows.append(
                    {"limit": limits[0], "offset": off, "error": exc.status, "msg": str(exc)[:160]}
                )
        self.report.pagination[label] = rows

    def check_drift(self, name: str, payload: Any, parser: Callable[[Any], Any]) -> None:
        targets = (
            payload
            if isinstance(payload, list)
            else ([payload] if isinstance(payload, dict) else [])
        )
        if not targets:
            self.report.drift[name] = "no items to validate"
            return
        errors = []
        for it in targets[:50]:
            try:
                parser(it)
            except schemas.SchemaDriftError as exc:
                errors.append(str(exc)[:200])
        self.report.drift[name] = (
            f"OK ({len(targets[:50])} items parsed)"
            if not errors
            else f"DRIFT in {len(errors)}/{len(targets[:50])}: {errors[0]}"
        )

    def run(self) -> ProbeReport:
        c = self.c
        closed = self.step(
            "gamma_markets_closed",
            lambda: c.markets(limit=5, closed="true", order="volumeNum", ascending="false"),
        )
        opened = self.step(
            "gamma_markets_open",
            lambda: c.markets(
                limit=5, closed="false", active="true", order="volumeNum", ascending="false"
            ),
        )
        if closed is not None:
            self.check_drift("gamma_markets_closed", closed, schemas.parse_gamma_market)
            self.report.fee_fields["gamma_market_keys_with_fee"] = sorted(
                {k for m in _items(closed) if isinstance(m, dict) for k in m if "fee" in k.lower()}
            )
        if opened is not None:
            self.check_drift("gamma_markets_open", opened, schemas.parse_gamma_market)

        trades = self.step("data_trades_global", lambda: c.trades(limit=5))
        if trades is not None:
            self.check_drift("data_trades_global", trades, schemas.parse_trade)

        wallet = None
        for t in _items(trades):
            if isinstance(t, dict) and t.get("proxyWallet"):
                wallet = str(t["proxyWallet"])
                break
        token_open = None
        for m in _items(opened):
            try:
                _, toks = schemas.parse_gamma_market(m)
            except schemas.SchemaDriftError:
                continue
            if toks:
                token_open = toks[0].token_id
                break
        self.report.samples = {"wallet": wallet or "", "token_open": token_open or ""}

        if wallet:
            ut = self.step("data_trades_user", lambda: c.trades(user=wallet, limit=5))
            if ut is not None:
                self.check_drift("data_trades_user", ut, schemas.parse_trade)
            self.step("data_positions", lambda: c.positions(wallet, limit=5))
            self.step("data_activity", lambda: c.activity(wallet, limit=5))
            now = int(time.time())
            self.step(
                "data_activity_window",
                lambda: c.activity(wallet, limit=5, start=now - 30 * 86400, end=now),
                save=False,
            )
            self.step("data_value", lambda: c.value(wallet))
        if token_open:
            book = self.step("clob_book", lambda: c.book(token_open))
            if book is not None:
                self.check_drift("clob_book", book, schemas.parse_book)
            self.step("clob_price", lambda: c.price(token_open, "BUY"))
            self.step("clob_midpoint", lambda: c.midpoint(token_open))
            self.step(
                "clob_prices_history",
                lambda: c.prices_history(token_open, interval="max", fidelity=60),
            )
            # UNVERIFIED endpoint: does the CLOB expose a per-token fee rate publicly?
            fee = self.step(
                "clob_fee_rate",
                lambda: c.http.get_json(f"{c.clob}/fee-rate", {"token_id": token_open}),
            )
            self.report.fee_fields["clob_fee_rate_response"] = fee

        self.paginate(
            "gamma_markets",
            lambda **p: c.markets(closed="true", **p),
            [100, 500, 1000],
            [0, 10_000, 100_000],
        )
        self.paginate(
            "data_trades",
            lambda **p: c.trades(**p),
            [100, 500, 1000, 10_000],
            [0, 1_000, 3_000, 10_000, 100_000],
        )
        if wallet:
            self.paginate(
                "data_activity_user",
                lambda **p: c.activity(wallet, **p),
                [100, 500, 1000],
                [0, 1_000, 10_000],
            )
        return self.report


def render_markdown(r: ProbeReport) -> str:
    when = time.strftime("%Y-%m-%d %H:%M:%SZ", time.gmtime(r.started_ts))
    n_ok = sum(s.ok for s in r.steps)
    status = (
        "VERIFIED against live API"
        if n_ok == len(r.steps)
        else (f"PARTIAL: {n_ok}/{len(r.steps)} endpoints reachable")
    )
    out = [BEGIN, "", f"## Probe findings ({status} at {when})", ""]
    out += ["| step | ok | HTTP | items | rate-limit headers | note |", "|---|---|---|---|---|---|"]
    for s in r.steps:
        hdr = ", ".join(f"{k}={v}" for k, v in s.headers.items()) or "-"
        out.append(
            f"| {s.name} | {'yes' if s.ok else 'NO'} | {s.status} | "
            f"{s.count if s.count is not None else '-'} | {hdr} | {s.note[:80]} |"
        )
    out += ["", "### Schema drift vs adapter layer (`data/schemas.py`)", ""]
    out += [f"- **{k}**: {v}" for k, v in r.drift.items()] or ["- (nothing checked)"]
    out += ["", "### Pagination", ""]
    for label, rows in r.pagination.items():
        out.append(
            f"- **{label}**: "
            + "; ".join(
                f"limit={x['limit']} offset={x['offset']} -> "
                + (str(x["returned"]) if "returned" in x else f"HTTP {x.get('error')}")
                for x in rows
            )
        )
    out += [
        "",
        "### Fee-related fields",
        "",
        "```json",
        json.dumps(r.fee_fields, indent=1, default=str)[:3000],
        "```",
        "",
    ]
    out += ["### Key shapes", ""]
    for s in r.steps:
        if s.ok and s.shape is not None:
            out += [
                f"<details><summary>{s.name}</summary>",
                "",
                "```json",
                json.dumps(s.shape, indent=1)[:4000],
                "```",
                "</details>",
                "",
            ]
    out.append(END)
    return "\n".join(out)


def write_assumptions(path: Path, section: str) -> None:
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    if BEGIN in text and END in text:
        pre, rest = text.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        text = pre + section + post
    else:
        text = text.rstrip() + "\n\n" + section + "\n"
    path.write_text(text, encoding="utf-8")
